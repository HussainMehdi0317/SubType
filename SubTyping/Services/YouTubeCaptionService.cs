using YoutubeExplode;
using YoutubeExplode.Videos;
using YoutubeExplode.Videos.ClosedCaptions;

namespace SubTyping;

public sealed class YouTubeCaptionService : IYouTubeCaptionService
{
    private readonly YoutubeClient client = new();

    public async Task<IReadOnlyList<YouTubeCaptionTrack>> GetTracksAsync(
        string url,
        CancellationToken cancellationToken = default)
    {
        var videoId = VideoId.Parse(url);
        var manifest = await client.Videos.ClosedCaptions.GetManifestAsync(videoId);

        return manifest.Tracks
            .OrderBy(track => track.IsAutoGenerated)
            .ThenBy(track => track.Language.Name)
            .Select(track => new YouTubeCaptionTrack(
                track.Language.Code,
                $"{track.Language.Name}{(track.IsAutoGenerated ? " (auto-generated)" : string.Empty)}",
                track.IsAutoGenerated,
                track))
            .ToArray();
    }

    public async Task<IReadOnlyList<PracticeLine>> GetLinesAsync(
        YouTubeCaptionTrack track,
        CancellationToken cancellationToken = default)
    {
        if (track.Track is not ClosedCaptionTrackInfo trackInfo)
        {
            throw new InvalidOperationException("The selected caption track is invalid.");
        }

        var captions = await client.Videos.ClosedCaptions.GetAsync(trackInfo);

        var usable = captions.Captions
            .Select(caption => new PracticeLine(
                caption.Text.Trim(),
                caption.Offset,
                caption.Offset + caption.Duration))
            .Where(line => line.Text.Length > 0)
            .ToArray();
        return usable;
    }
}
